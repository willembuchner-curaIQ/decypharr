package par2test

import (
	"bytes"
	"testing"
)

func TestRecoverySetGolden(t *testing.T) {
	data := [][]byte{
		{0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07},
		{0xf0, 0xe1, 0xd2, 0xc3, 0xb4, 0xa5, 0x96, 0x87},
		{0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88},
	}
	want := [][]byte{
		{0xe1, 0xc2, 0xe3, 0x84, 0xe5, 0xc6, 0xe7, 0x08},
		{0xdb, 0xb4, 0x4d, 0x3a, 0xa4, 0xb9, 0x6a, 0x37},
		{0x02, 0xeb, 0x9c, 0xc0, 0xbe, 0xb9, 0xa0, 0x97},
		{0x9e, 0xd3, 0x40, 0xf1, 0x22, 0xce, 0xfc, 0xb4},
		{0xf2, 0x66, 0xcf, 0xf4, 0xa4, 0x82, 0xbe, 0xc0},
		{0xa5, 0x42, 0xe6, 0x08, 0x2c, 0x04, 0x60, 0x9c},
	}
	got := RecoverySet(data, len(want))
	for exponent := range want {
		if !bytes.Equal(got[exponent], want[exponent]) {
			t.Fatalf("exponent %d = %x, want %x", exponent, got[exponent], want[exponent])
		}
	}
}
